// Usage: node scripts/generate-character-encoding.ts
// Imports mapping data and generates explicit descriptors. Runtime codecs are implemented locally.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

if (process.argv.length > 2) {
  throw new Error("No arguments expected; uses the installed effect dev dependency iconv-lite")
}
const effectDirectory = fileURLToPath(new URL("../packages/effect/", import.meta.url))
const effectRequire = createRequire(resolve(effectDirectory, "package.json"))
const packagePath = effectRequire.resolve("iconv-lite/package.json")
const upstream = dirname(packagePath)
const require = createRequire(packagePath)
const revision = (require("./package.json") as { version: string }).version
const license = readFileSync(resolve(upstream, "LICENSE"), "utf8")
const directory = resolve(effectDirectory, "src/internal/characterEncoding")
mkdirSync(directory, { recursive: true })
const publicDirectory = resolve(effectDirectory, "src/encoding")
mkdirSync(publicDirectory, { recursive: true })
const header =
  `/*\n * Mapping data from iconv-lite ${revision}.\n * Generated by scripts/generate-character-encoding.ts; do not edit.\n *\n${
    license.trim().split("\n").map((line) => ` * ${line}`).join("\n")
  }\n */\n`
const single = { ...require("./encodings/sbcs-data"), ...require("./encodings/sbcs-data-generated") }
const definitions: Record<string, string> = {}
const aliases: Record<string, string> = {}
for (const [name, value] of Object.entries(single)) {
  if (typeof value === "string") aliases[name] = value
  else if (typeof value === "object" && value !== null && "chars" in value) {
    definitions[name] = String(value.chars)
  }
}
for (const [name, chars] of Object.entries(definitions)) {
  writeFileSync(resolve(directory, name + "Data.ts"), header + "export default " + JSON.stringify(chars) + "\n")
}

const multi = require("./encodings/dbcs-data")
const names: Array<string> = []
const multiAliases: Record<string, string> = {}
for (const [name, value] of Object.entries(multi)) {
  if (typeof value === "string") multiAliases[name] = value
  else if (typeof value === "object" && value !== null && "table" in value) {
    const item = value as {
      table: () => unknown
      encodeAdd?: unknown
      encodeSkipVals?: unknown
      gb18030?: () => unknown
    }
    const data = {
      table: item.table(),
      encodeAdd: item.encodeAdd,
      encodeSkipVals: item.encodeSkipVals,
      ranges: item.gb18030?.()
    }
    names.push(name)
    writeFileSync(
      resolve(directory, `${name}Data.ts`),
      `${header}import type { Mapping } from "./types.ts"\nconst data: Mapping = ${
        JSON.stringify(data)
      }\nexport default data\n`
    )
  }
}

const unicode: Record<string, ReadonlyArray<string>> = {
  utf8: ["unicode11utf8"],
  utf16le: ["ucs2", "ucs2le"],
  utf16be: ["ucs2be"],
  utf32le: ["ucs4le"],
  utf32be: ["ucs4be"]
}
const all = [...Object.keys(unicode), ...Object.keys(definitions), ...names].sort()
const canonical = new Set(all)
const allAliases = { ...aliases, ...multiAliases }
const aliasesFor = (name: string) =>
  Object.keys(allAliases).filter((alias) => {
    let target = alias
    const seen = new Set<string>()
    while (!canonical.has(target) && !seen.has(target)) {
      seen.add(target)
      if (!Object.hasOwn(allAliases, target)) return false
      target = allAliases[target]
    }
    return target === name && alias !== name
  })
const special: Record<string, string> = {
  utf8: "Utf8",
  utf16le: "Utf16LE",
  utf16be: "Utf16BE",
  utf32le: "Utf32LE",
  utf32be: "Utf32BE",
  shiftjis: "ShiftJis",
  eucjp: "EucJp",
  big5hkscs: "Big5Hkscs",
  gbk: "Gbk",
  gb18030: "Gb18030"
}
const moduleName = (name: string): string =>
  special[name] ?? (/^cp125[0-8]$/.test(name) ? "Windows" + name.slice(2) : name[0].toUpperCase() + name.slice(1))
if (new Set(all.map(moduleName)).size !== all.length) throw new Error("Duplicate codec module names")
const doc = (text: string, category?: string) =>
  "/**\n * " + text + "\n *\n" + (category ? " * @category " + category + "\n" : "") + " * @since 4.0.0\n */\n"
const generated = "// Generated by scripts/generate-character-encoding.ts; do not edit.\n"
for (const name of all) {
  const isUnicode = Object.hasOwn(unicode, name)
  const isSingle = Object.hasOwn(definitions, name)
  const engine = isSingle ? "SingleByte" : "MultiByte"
  const dataImport = isUnicode
    ? "import * as Unicode from \"../internal/characterEncoding/unicode.ts\"\n"
    : "import data from \"../internal/characterEncoding/" + name + "Data.ts\"\nimport { " + engine +
      " } from \"../internal/characterEncoding/" + (isSingle ? "singleByte" : "multiByte") + ".ts\"\n"
  const factory = isUnicode
    ? "() => ({ encoder: (options) => Unicode.encoder(\"" + name +
      "\", options), decoder: (options) => Unicode.decoder(\"" + name + "\", options) }), true"
    : "() => new " + engine + "(data)"

  const capitalizedName = name[0].toUpperCase() + name.slice(1).toUpperCase()
  const displayName = special[name] ? special[name].replace(/([A-Z])/g, "-$1").slice(1) : capitalizedName

  writeFileSync(
    resolve(publicDirectory, moduleName(name) + ".ts"),
    doc(displayName + " character encoding with typed failures and Effect streams.") + generated +
      "import type { CharacterEncodingError, Encoding, Options } from \"../CharacterEncoding.ts\"\nimport * as Effect from \"../Effect.ts\"\nimport { make } from \"../internal/characterEncoding/codec.ts\"\nimport { concat } from \"../internal/characterEncoding/types.ts\"\n" +
      dataImport +
      "import * as Stream from \"../Stream.ts\"\n\n" +
      doc("The " + name + " encoding descriptor. For registry use only.", "encodings") +
      "export const encoding: Encoding = /* @__PURE__ */ make(\"" + name + "\", " +
      JSON.stringify(isUnicode ? unicode[name] : aliasesFor(name)) + ", " + factory + ")\n\n" +
      "const attempt = <A>(operation: \"encode\" | \"decode\", f: () => A): A => {\n" +
      "  try {\n" +
      "    return f()\n" +
      "  } catch (cause) {\n" +
      "    throw {\n" +
      "      encoding: \"" + name + "\",\n" +
      "      operation,\n" +
      "      message: String(cause),\n" +
      "      cause,\n" +
      "      _tag: \"CharacterEncodingError\"\n" +
      "    }\n" +
      "  }\n" +
      "}\n\n" +
      doc("Encodes a complete string to " + name + " bytes, throwing CharacterEncodingError on failure.", "encoding") +
      "export const encodeUnsafe = (text: string, options?: Options): Uint8Array => {\n" +
      "  const encoder = attempt(\"encode\", () => encoding.makeEncoder(options ?? {}))\n" +
      "  return attempt(\"encode\", () => concat(encoder.write(text), encoder.end()))\n" +
      "}\n\n" +
      doc("Decodes complete " + name + " bytes to a string, throwing CharacterEncodingError on failure.", "decoding") +
      "export const decodeUnsafe = (bytes: Uint8Array, options?: Options): string => {\n" +
      "  const decoder = attempt(\"decode\", () => encoding.makeDecoder(options ?? {}))\n" +
      "  return attempt(\"decode\", () => decoder.write(bytes) + decoder.end())\n" +
      "}\n\n" +
      doc("Encodes a string to " + name + " bytes with conversion errors in the Effect error channel.", "encoding") +
      "export const encode = (\n" +
      "  text: string,\n" +
      "  options?: Options\n" +
      "): Effect.Effect<Uint8Array, CharacterEncodingError> =>\n" +
      "  Effect.try({ try: () => encodeUnsafe(text, options), catch: (error) => error as CharacterEncodingError })\n\n" +
      doc("Decodes " + name + " bytes to a string with conversion errors in the Effect error channel.", "decoding") +
      "export const decode = (\n" +
      "  bytes: Uint8Array,\n" +
      "  options?: Options\n" +
      "): Effect.Effect<string, CharacterEncodingError> =>\n" +
      "  Effect.try({ try: () => decodeUnsafe(bytes, options), catch: (error) => error as CharacterEncodingError })\n\n" +
      doc(
        "Encodes a stream of strings to " + name + " bytes incrementally, preserving codec state across chunks.",
        "streaming"
      ) +
      "export const encodeStream = <E, R>(options?: Options) =>\n" +
      "  (self: Stream.Stream<string, E, R>): Stream.Stream<Uint8Array, E | CharacterEncodingError, R> =>\n" +
      "    Stream.unwrap(Effect.map(\n" +
      "      Effect.try({\n" +
      "        try: () => attempt(\"encode\", () => encoding.makeEncoder(options ?? {})),\n" +
      "        catch: (error) => error as CharacterEncodingError\n" +
      "      }),\n" +
      "      (encoder) =>\n" +
      "        Stream.concat(\n" +
      "          Stream.mapEffect(self, (text) =>\n" +
      "            Effect.try({\n" +
      "              try: () => encoder.write(text),\n" +
      "              catch: (error) => error as CharacterEncodingError\n" +
      "            })),\n" +
      "          Stream.fromEffect(Effect.try({\n" +
      "            try: () => encoder.end(),\n" +
      "            catch: (error) => error as CharacterEncodingError\n" +
      "          }))\n" +
      "        )\n" +
      "    ))\n\n" +
      doc(
        "Decodes a stream of " + name + " bytes to strings incrementally, retaining partial sequences across chunks.",
        "streaming"
      ) +
      "export const decodeStream = <E, R>(options?: Options) =>\n" +
      "  (self: Stream.Stream<Uint8Array, E, R>): Stream.Stream<string, E | CharacterEncodingError, R> =>\n" +
      "    Stream.unwrap(Effect.map(\n" +
      "      Effect.try({\n" +
      "        try: () => attempt(\"decode\", () => encoding.makeDecoder(options ?? {})),\n" +
      "        catch: (error) => error as CharacterEncodingError\n" +
      "      }),\n" +
      "      (decoder) =>\n" +
      "        Stream.concat(\n" +
      "          Stream.mapEffect(self, (bytes) =>\n" +
      "            Effect.try({\n" +
      "              try: () => decoder.write(bytes),\n" +
      "              catch: (error) => error as CharacterEncodingError\n" +
      "            })),\n" +
      "          Stream.fromEffect(Effect.try({\n" +
      "            try: () => decoder.end(),\n" +
      "            catch: (error) => error as CharacterEncodingError\n" +
      "          }))\n" +
      "        )\n" +
      "    ))\n"
  )
}
let registry = doc("Opt-in registry of every encoding. Use individual codec modules for selective bundles.") +
  generated +
  "import { makeRegistry } from \"../CharacterEncoding.ts\"\nimport type { Registry } from \"../CharacterEncoding.ts\"\n" +
  all.map((name) => "import * as " + moduleName(name) + " from \"./" + moduleName(name) + ".ts\"").join("\n") + "\n" +
  doc("All built-in encodings and aliases. Resolution does not construct lookup tables.", "encodings") +
  "export const registry: Registry = /* @__PURE__ */ makeRegistry([" +
  all.map((name) => moduleName(name) + ".encoding").join(", ") + "])\n"
for (
  const [name, description] of [
    ["encodings", "All canonical codec descriptors."],
    ["resolve", "Resolves a label with CharacterEncodingError in the Effect error channel."],
    ["resolveUnsafe", "Resolves a label synchronously, throwing CharacterEncodingError when unknown."],
    ["encodingExists", "Tests whether a label is supported by this registry."]
  ]
) {
  registry += doc(description, "encodings") + "export const " + name + ": Registry[\"" + name + "\"] = registry." +
    name + "\n"
}
writeFileSync(resolve(publicDirectory, "All.ts"), registry)
console.log("Generated " + all.length + " explicit codec modules and mapping data from " + revision)
