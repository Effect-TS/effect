/**
 * The types and descriptors of Google's
 * `google/protobuf/compiler/plugin.proto`: the `CodeGeneratorRequest` that
 * protoc and buf write to a plugin's standard input, and the
 * `CodeGeneratorResponse` that the plugin answers with on standard output.
 *
 * **Mental model**
 *
 * - Per message, an interface of its values and a `MessageDescriptor` of the
 *   same name, for `ProtobufMessage.decode` and `ProtobufMessage.encode`.
 * - `pluginFile` is the resolved file, linked to
 *   `ProtobufDescriptorProto.descriptorFile`.
 * - The definitions are the output of `protoc-gen-effect` from
 *   `@effect/protobuf-generator` for protoc 36.2's descriptor of the file.
 *   The plugin reads its own requests with them.
 *
 * **Example** (Answering a plugin request)
 *
 * ```ts import.meta.vitest
 * import { Result } from "effect"
 * import { ProtobufMessage, ProtobufPluginProto } from "effect/protobuf"
 *
 * const respond = (request: ProtobufPluginProto.CodeGeneratorRequest): ProtobufPluginProto.CodeGeneratorResponse => ({
 *   file: (request.file_to_generate ?? []).map((name) => ({ name: `${name}.txt`, content: name }))
 * })
 *
 * const input = Result.getOrThrow(ProtobufMessage.encode(ProtobufPluginProto.CodeGeneratorRequest)({
 *   file_to_generate: ["a.proto"]
 * }))
 * const request = Result.getOrThrow(ProtobufMessage.decode(ProtobufPluginProto.CodeGeneratorRequest)(input))
 * respond(request as ProtobufPluginProto.CodeGeneratorRequest).file?.[0].name // => "a.proto.txt"
 * ```
 *
 * @stability experimental
 * @since 4.1.5
 */

