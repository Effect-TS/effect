/**
 * The types and descriptors of Google's `google/protobuf/descriptor.proto`:
 * the `FileDescriptorProto`s that describe protobuf files, messages, fields,
 * enums and services, as protoc, buf, gRPC server reflection and protoc
 * plugins exchange them.
 *
 * **Mental model**
 *
 * - Per message, an interface of its values and a `MessageDescriptor` of the
 *   same name, such as `FileDescriptorProto`, for `ProtobufMessage`. Nested
 *   types are named `Outer_Inner`, such as `DescriptorProto_ExtensionRange`.
 * - Per enum, an object of its numbers by name and the type of its values,
 *   such as `FieldDescriptorProto_Type`.
 * - `descriptorFile` is the resolved file, which files importing
 *   `descriptor.proto` pass to `ProtobufDescriptor.make` as a dependency.
 * - The definitions are the output of `protoc-gen-effect` from
 *   `@effect/protobuf-generator` for protoc 36.2's descriptor of the file.
 *
 * **Example** (Reading a descriptor set)
 *
 * ```ts import.meta.vitest
 * import { Result } from "effect"
 * import { ProtobufDescriptorProto, ProtobufMessage } from "effect/protobuf"
 *
 * const set: ProtobufDescriptorProto.FileDescriptorSet = {
 *   file: [{ name: "point.proto", syntax: "proto3", message_type: [{ name: "Point" }] }]
 * }
 * const bytes = Result.getOrThrow(ProtobufMessage.encode(ProtobufDescriptorProto.FileDescriptorSet)(set))
 *
 * const registry = Result.getOrThrow(ProtobufDescriptorProto.fromFileDescriptorSet(bytes))
 * registry.getMessage("Point")?.name // => "Point"
 * ```
 *
 * @stability experimental
 * @since 4.1.5
 */
import * as Result from "../Result.ts"
import { FileDescriptorSet } from "./internal/generated/google/protobuf/descriptor.proto.ts"
import * as ProtobufDescriptor from "./ProtobufDescriptor.ts"
import * as ProtobufMessage from "./ProtobufMessage.ts"

/**
 * The definitions of `descriptor.proto`, generated by `protoc-gen-effect`.
 *
 * @stability experimental
 * @since 4.1.5
 */
export * from "./internal/generated/google/protobuf/descriptor.proto.ts"

/**
 * Decodes a `FileDescriptorSet`, as `protoc --descriptor_set_out` and
 * `buf build` write it, and resolves its files into a registry.
 *
 * @stability experimental
 * @category constructors
 * @since 4.1.5
 */
export const fromFileDescriptorSet = (
  bytes: Uint8Array
): Result.Result<ProtobufDescriptor.Registry, ProtobufDescriptor.ProtobufDescriptorError> => {
  const set = ProtobufMessage.decode(FileDescriptorSet)(bytes)
  if (Result.isFailure(set)) {
    return Result.fail(new ProtobufDescriptor.ProtobufDescriptorError({ message: set.failure.message }))
  }
  return ProtobufDescriptor.make((set.success as FileDescriptorSet).file ?? [])
}
