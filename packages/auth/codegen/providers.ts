import * as GraphQLGenerator from "@effect/graphql-generator/Generator"
import * as Command from "effect/cli/Command"
import * as Console from "effect/Console"
import * as Digest from "effect/crypto/Digest"
import * as Effect from "effect/Effect"
import * as FileSystem from "effect/FileSystem"
import * as HttpClient from "effect/http/HttpClient"
import * as Path from "effect/Path"
import * as ChildProcess from "effect/process/ChildProcess"
import * as Schema from "effect/Schema"
import * as Stream from "effect/Stream"
import * as Profiles from "./profiles.ts"

class ProviderCodegenError extends Schema.TaggedError<ProviderCodegenError>()("ProviderCodegenError", {
  message: Schema.String,
  cause: Schema.optionalKey(Schema.Defect())
}) {}

const Source = Schema.Struct({
  project: Schema.String,
  version: Schema.optionalKey(Schema.String),
  commit: Schema.optionalKey(Schema.String),
  url: Schema.String,
  sha256: Schema.String,
  license: Schema.String
})
const Sources = Schema.Record(Schema.String, Source)
const generated = "src/oauth/providers/internal/generated"
const header = "// Generated by packages/auth/codegen/bin.ts. Do not edit.\n"
  + "// Sources and licenses: packages/auth/codegen/sources.json and THIRD_PARTY_NOTICES.md.\n"

const locations = Effect.gen(function*() {
  const path = yield* Path.Path
  const directory = yield* path.fromFileUrl(new URL(".", import.meta.url))
  const packageRoot = path.resolve(directory, "..")
  return { directory, packageRoot, repositoryRoot: path.resolve(packageRoot, "../..") }
})

const readSources = Effect.gen(function*() {
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path
  const { directory } = yield* locations
  const contents = yield* fs.readFileString(path.resolve(directory, "sources.json"))
  return yield* Schema.decodeUnknownEffect(Schema.fromJsonString(Sources))(contents)
})

const format = Effect.fnUntraced(function*(contents: string) {
  const { repositoryRoot } = yield* locations
  const handle = yield* ChildProcess.make("pnpm", ["exec", "dprint", "fmt", "--stdin", "ts"], {
    cwd: repositoryRoot,
    stdin: Stream.make(new TextEncoder().encode(contents)),
    stderr: "inherit"
  })
  const output = yield* Stream.mkString(handle.stdout.pipe(Stream.decodeText()))
  const exitCode = yield* handle.exitCode
  if (exitCode !== 0) {
    return yield* new ProviderCodegenError({ message: `dprint exited with code ${exitCode}.` })
  }
  return output
}, Effect.scoped)

const generate = Effect.fnUntraced(function*(check: boolean) {
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path
  const client = HttpClient.filterStatusOk(yield* HttpClient.HttpClient)
  const digest = yield* Digest.Digest
  const { packageRoot } = yield* locations
  const sources = yield* readSources
  const inputs: Record<string, string> = {}
  for (const [name, source] of Object.entries(sources)) {
    const buffer = yield* client.get(source.url).pipe(
      Effect.flatMap((response) => response.arrayBuffer),
      Effect.timeout("60 seconds")
    )
    const bytes = new Uint8Array(buffer)
    if ((yield* digest.digestHex(Digest.sha256, bytes)) !== source.sha256) {
      return yield* new ProviderCodegenError({ message: `Upstream digest mismatch: ${name}` })
    }
    inputs[name] = new TextDecoder().decode(bytes)
  }

  const profiles = yield* Effect.try({
    try: () =>
      Profiles.generate(
        inputs,
        Object.fromEntries(Object.entries(sources).map(([name, source]) => [name, source.url]))
      ),
    catch: (cause) =>
      new ProviderCodegenError({
        message: `Unable to generate provider profiles: ${cause instanceof Error ? cause.message : String(cause)}`,
        cause
      })
  })
  const files: Array<GraphQLGenerator.GeneratedFile> = Object.entries(profiles).map(([name, contents]) => ({
    path: path.resolve(packageRoot, generated, name),
    contents
  }))
  const temporary = yield* fs.makeTempDirectoryScoped({ prefix: "effect-auth-codegen-" })
  const linearSchema = path.join(temporary, "linear.graphql")
  yield* fs.writeFileString(linearSchema, inputs.linear)
  const linear = yield* GraphQLGenerator.generate({
    schema: linearSchema,
    documents: [`${generated}/linear.graphql`],
    shared: `${generated}/linear.shared.ts`,
    importExtension: ".ts"
  }, { cwd: packageRoot })
  if (linear.diagnostics.length > 0) {
    return yield* new ProviderCodegenError({ message: JSON.stringify(linear.diagnostics) })
  }
  const expected = ["linear.graphql.ts", "linear.shared.ts"].map((name) => path.resolve(packageRoot, generated, name))
  if (
    linear.files.length !== expected.length || expected.some((path) => !linear.files.some((file) => file.path === path))
  ) {
    return yield* new ProviderCodegenError({
      message: "Expected the Linear viewer operation and shared schemas; check linear.graphql"
    })
  }
  files.push(...linear.files.map((file) => ({
    ...file,
    contents: header + file.contents.replace(
      "import { GraphQL, GraphQLGroup } from \"effect/graphql\"",
      "import * as GraphQL from \"effect/graphql/GraphQL\"\nimport * as GraphQLGroup from \"effect/graphql/GraphQLGroup\""
    )
  })))
  const formatted = yield* Effect.forEach(
    files,
    Effect.fnUntraced(function*(file) {
      return { ...file, contents: yield* format(file.contents) }
    })
  )
  for (const file of formatted) {
    if (check) {
      if ((yield* fs.readFileString(file.path)) !== file.contents) {
        return yield* new ProviderCodegenError({ message: `Stale generated file: ${file.path}` })
      }
    } else {
      yield* fs.makeDirectory(path.dirname(file.path), { recursive: true })
      yield* fs.writeFileString(file.path, file.contents)
    }
  }
  yield* Console.log(`${check ? "Checked" : "Generated"} ${files.length} provider schema modules.`)
}, Effect.scoped)

/** @internal */
export const cli = Command.make("auth-providers").pipe(
  Command.withDescription("Generate and check OAuth provider schemas from pinned upstream sources"),
  Command.withSubcommands([
    Command.make("generate", {}, () => generate(false)).pipe(
      Command.withDescription("Fetch pinned upstream schemas and generate provider modules")
    ),
    Command.make("check", {}, () => generate(true)).pipe(
      Command.withDescription(
        "Fetch pinned upstream schemas and check generated modules without changing repository files"
      )
    )
  ])
)
