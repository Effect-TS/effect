import * as JsonSchemaGenerator from "@effect/openapi-generator/JsonSchemaGenerator"
import { parse as parseYaml } from "yaml"
import * as Readers from "./readers.ts"

const header = "// Generated by packages/auth/codegen/bin.ts. Do not edit.\n"
  + "// Sources and licenses: packages/auth/codegen/sources.json and THIRD_PARTY_NOTICES.md.\n"
  + "import * as Schema from \"effect/Schema\"\n\n"

// Upstream defines the shapes. Auth owns bounds, formats and the fields exposed by each profile.
function shape(input: Readers.Model): Readers.Model {
  const output: Readers.Model = Object.fromEntries(
    ["type", "const", "enum", "required", "not"].flatMap((key) => input[key] === undefined ? [] : [[key, input[key]]])
  )
  if (input.properties !== undefined) {
    output.properties = Object.fromEntries(
      Object.entries(input.properties).map(([name, field]) => [name, shape(field)])
    )
    output.additionalProperties = false
  }
  if (input.items !== undefined) output.items = shape(input.items)
  for (const key of ["anyOf", "oneOf"] as const) {
    if (input[key] !== undefined) output[key] = input[key].map(shape)
  }
  if (input.additionalProperties !== undefined && input.properties === undefined) {
    output.additionalProperties = typeof input.additionalProperties === "boolean"
      ? input.additionalProperties
      : shape(Readers.record(input.additionalProperties, "additionalProperties"))
  }
  return output
}

function render(models: Readonly<Record<string, Readers.Model>>): string {
  const generator = JsonSchemaGenerator.make()
  for (const [name, model] of Object.entries(models)) generator.addSchema(name, model)
  // Existing auth bounds count UTF-16 code units, not JSON Schema's code points.
  return header + generator.generate("openapi-3.1", {}, false)
    .replaceAll("Schema.isMaxCodePoints(", "Schema.isMaxLength(")
    .replaceAll("Schema.isMinCodePoints(", "Schema.isMinLength(")
    .replaceAll(" code points", " UTF-16 code units")
}

// Separate field exports allow unused upstream fields to be removed from consumer bundles.
function fields(models: Readonly<Record<string, Readers.Model>>): string {
  const schemas: Record<string, Readers.Model> = {}
  for (const [prefix, model] of Object.entries(models)) {
    if (model.type !== "object" || model.properties === undefined) throw new Error(`Expected fields for ${prefix}`)
    for (const [name, field] of Object.entries(model.properties)) {
      const identifier = `${prefix}_${name.replaceAll(/[^a-zA-Z0-9_$]/gu, "_")}`
      if (Object.hasOwn(schemas, identifier)) throw new Error(`Duplicate generated identifier: ${identifier}`)
      schemas[identifier] = shape(field)
    }
  }
  return render(schemas)
}

function githubPolicy(schema: Readers.Model, path: ReadonlyArray<string> = []): void {
  for (const key of ["description", "example", "examples", "title", "format"]) delete schema[key]
  if (schema.type === "string") {
    schema.maxLength = path.length === 1 && ["login", "name"].includes(path[0]) ?
      256
      : path.length === 1 && ["email", "notification_email"].includes(path[0])
      ? 320
      : 2048
    if (path.length === 1 && path[0] === "login") schema.minLength = 1
  } else if (schema.type === "integer") {
    schema.minimum = path.length === 1 && path[0] === "id" ? 1 : 0
    schema.maximum = Number.MAX_SAFE_INTEGER
  } else if (schema.type === "object") {
    schema.additionalProperties = false
    for (const [name, field] of Object.entries(schema.properties ?? {})) githubPolicy(field, [...path, name])
  }
  for (const part of schema.anyOf ?? []) githubPolicy(part, path)
}

function openIdPolicy(schema: Readers.Model, path: ReadonlyArray<string> = []): void {
  if (schema.type === "string") {
    schema.maxLength = ["profile", "picture", "website", "formatted", "street_address"].includes(path.at(-1)!) ?
      2048
      : path.at(-1) === "email"
      ? 320
      : 256
  } else if (schema.type === "number") {
    schema.type = "integer"
    schema.minimum = 0
    schema.maximum = Number.MAX_SAFE_INTEGER
  } else if (schema.type === "object") {
    schema.additionalProperties = false
    for (const [name, field] of Object.entries(schema.properties ?? {})) openIdPolicy(field, [...path, name])
  }
}

/** @internal */
export function generate(inputs: Readonly<Record<string, string>>, urls: Readonly<Record<string, string>>) {
  const api = (name: string, path: ReadonlyArray<string>, yaml = false) =>
    Readers.openApi(
      yaml ? parseYaml(inputs[name]) : JSON.parse(inputs[name]),
      path,
      urls[name]
    )
  const github = api("github", ["components", "schemas", "private-user"])
  github.required = ["id"]
  githubPolicy(github)
  const openid = Readers.openId(inputs.openid)
  delete openid.properties!.sub
  openIdPolicy(openid)
  const read = Readers.typescript({
    "/dropbox.ts": inputs.dropbox,
    "/notion/common.ts": inputs["notion-common"],
    "/notion/oauth.ts": inputs["notion-oauth"],
    "/google.ts": inputs.google,
    "/microsoft.ts": inputs.microsoft,
    "/slack/types/response/OpenIDConnectUserInfoResponse.ts": inputs.slack,
    "/slack/WebClient.ts": inputs["slack-client"]
  })
  return {
    "github.ts": render({ Profile: github }),
    "openid.ts": render({ Profile: openid }),
    "figma.ts": fields({
      User: api("figma", ["components", "responses", "GetMeResponse", "content", "application/json", "schema"], true)
    }),
    "kick.ts": fields({ User: api("kick", ["definitions", "endpoints.GetUser"]) }),
    "strava.ts": fields({ Athlete: api("strava", ["SummaryAthlete"]) }),
    "x.ts": fields({ User: api("x", ["components", "schemas", "User"]) }),
    "dropbox.ts": fields({ Account: read("/dropbox.ts", "users.FullAccount") }),
    "notion.ts": fields({
      User: read("/notion/common.ts", "UserObjectResponseCommon"),
      Person: read("/notion/common.ts", "PersonUserObjectResponse"),
      Bot: read("/notion/common.ts", "BotUserObjectResponse"),
      Token: read("/notion/oauth.ts", "OauthTokenResponse")
    }),
    "google.ts": fields({ Claims: read("/google.ts", "TokenPayload") }),
    "microsoft.ts": fields({ Claims: read("/microsoft.ts", "TokenClaims") }),
    "slack.ts": fields({
      Claims: read("/slack/types/response/OpenIDConnectUserInfoResponse.ts", "OpenIDConnectUserInfoResponse")
    })
  }
}
